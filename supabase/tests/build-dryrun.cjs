// Builds supabase/tests/permissions.dryrun.sql: BEGIN; the Slice 0b migration; the permission
// tests; ROLLBACK. Paste the result into the Supabase dashboard SQL editor to try the migration
// without keeping any of it.
//
//   node supabase/tests/build-dryrun.cjs
//
// Re-run it whenever the migration or permissions.test.sql changes.
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const migrationFile = path.join(root, 'migrations', '20261014000000_slice0b_permissions.sql')
const testsFile = path.join(__dirname, 'permissions.test.sql')
const outFile = path.join(__dirname, 'permissions.dryrun.sql')

const read = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
const migration = read(migrationFile)
const tests = read(testsFile)

// Statements that cannot run inside a transaction block (comment lines are ignored).
const NOT_IN_TRANSACTION = [
  /create\s+(unique\s+)?index\s+concurrently/i,
  /drop\s+index\s+concurrently/i,
  /reindex\s+.*concurrently/i,
  /alter\s+type\s+.*add\s+value/i,
  /\bvacuum\b/i,
  /create\s+database/i,
  /drop\s+database/i,
  /create\s+tablespace/i,
  /alter\s+system/i,
  /\bcluster\b/i,
  // A top-level transaction statement (PL/pgSQL "begin" has no semicolon).
  /^\s*(begin|commit|rollback|start\s+transaction)\s*;/im,
]
const code = migration
  .split('\n')
  .filter((line) => !line.trim().startsWith('--'))
  .join('\n')
for (const pattern of NOT_IN_TRANSACTION) {
  if (pattern.test(code)) {
    console.error(`The migration contains something that cannot run inside a transaction: ${pattern}`)
    process.exit(1)
  }
}

const start = tests.indexOf('-- ===== BEGIN TESTS =====')
const end = tests.indexOf('-- ===== END TESTS =====')
if (start < 0 || end < start) {
  console.error('permissions.test.sql is missing its BEGIN TESTS / END TESTS markers')
  process.exit(1)
}
const body = tests.slice(start, end)

const out = `-- DRY RUN for Slice 0b. Paste the whole file into the Supabase dashboard SQL editor and run it.
--
-- BEGIN; the migration; the permission tests; ROLLBACK. Nothing persists: the migration is
-- undone and the test users, firms and clients are never committed. No real data is read or
-- changed. Read the NOTICE lines: 'PASS: <name>' per check, then 'ALL PERMISSION TESTS PASSED'.
-- A failure stops the script with an error 'FAIL: <name>: <detail>' and the transaction is
-- abandoned.
--
-- Generated by supabase/tests/build-dryrun.cjs from:
--   supabase/migrations/20261014000000_slice0b_permissions.sql
--   supabase/tests/permissions.test.sql

begin;

-- ##### MIGRATION: 20261014000000_slice0b_permissions.sql #####

${migration.trim()}

-- ##### PERMISSION TESTS #####

${body.trim()}

rollback;
`
fs.writeFileSync(outFile, out)
console.log(`wrote ${path.relative(process.cwd(), outFile)} (${out.split('\n').length} lines)`)
